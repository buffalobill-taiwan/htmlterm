import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
let source = await readFile(new URL('../js/cmd/cardgames/regicide/RegicideGame.js', import.meta.url), 'utf8');
source = source.replace(/^import .*;$/gm, '').replace('export class', 'class');
const flights = [];
const dealCard = (cmd, card, from, to, options, done) => {
    const flight = { card, from, to, options, done, cancelled: false };
    flights.push(flight);
    return () => { flight.cancelled = true; };
};
const Game = new Function('dealCard', 'VirtualBuffer', source + '\nreturn RegicideGame;')(dealCard, class {});
const game = new Game({});
game.draw = () => {};
const cards = Array.from({length: 8}, (_, rank) => ({rank, suit: 0}));
game.state = {hand: cards};
game.dealNewCards([]);
assert.equal(flights.length, 1);
assert.equal(game.hidden.size, 8);
for (let i = 0; i < 8; i++) {
    flights[i].options.onStep(1, 0.45);
    assert.deepEqual(flights[i].to, {x: 3 + i * 9, y: 12});
    assert.deepEqual(flights[i].from, {x: 73, y: 5});
}
assert.equal(game.pending, 0);
assert.equal(game.hidden.size, 8);
for (const f of flights) f.done();
assert.equal(game.dealing, false);
assert.equal(game.hidden.size, 0);
flights.length = 0;
game.dealNewCards(cards.slice(0, 6));
assert.equal(game.hidden.size, 2);
const stale = flights[0];
game.stopDeals();
assert.equal(stale.cancelled, true);
stale.options.onStep(1, 1); stale.done();
assert.equal(flights.length, 1);
game.dealNewCards(cards);
assert.equal(game.dealing, false);
assert.equal(flights.length, 1);
game.dealNewCards([]);
const last = flights.at(-1);
game.dispose();
assert.equal(last.cancelled, true);
last.done();
assert.equal(game.hidden.size, 0);
console.log('Regicide animation tests passed');
const recoveryGame = new Game({});
recoveryGame.draw = () => {};
recoveryGame.state = {hand: cards.slice(0, 2)};
flights.length = 0;
recoveryGame.recoverCards([], {count: 2, deckCount: 2, discard: []});
assert.equal(flights[0].options.faceDown, true);
assert.deepEqual(flights[0].from, {x: 63, y: 5});
flights[0].options.onStep(1, 0.45);
flights[0].done();
assert.equal(flights.length, 2); // No draw before both recoveries land.
flights[1].done();
assert.equal(flights.length, 3);
assert.deepEqual(flights[2].from, {x: 73, y: 5});
assert.equal(recoveryGame.recovering, false);
recoveryGame.dispose();
assert.equal(flights[2].cancelled, true);
const collector = new Game({});
collector.draw = () => {};
collector.state = {hand: [], enemy: {suit: 1, rank: 12}};
let arrival;
collector.showEvent = (text, done) => { arrival = text; done(); };
flights.length = 0;
collector.collectUsed({used: cards.slice(0, 2), enemy: cards[7],
    deckCount: 4, discard: cards.slice(0, 2)});
assert.equal(collector.collecting, true);
assert.equal(flights[0].options.faceUp, true);
assert.deepEqual(flights[0].from, {x: 53, y: 5});
assert.deepEqual(flights[0].to, {x: 63, y: 5});
flights[0].options.onStep(1, 0.45);
flights[0].done();
assert.equal(collector.dealing, true);
flights[1].done();
assert.equal(collector.dealing, false);
assert.equal(collector.displayEnemy, null);
assert.equal(arrival, '♥Q來襲！');
collector.collectUsed({used: cards.slice(0, 1), enemy: cards[7], deckCount: 4, discard: cards.slice(0, 1)});
const cancelledCollection = flights.at(-1);
collector.dispose();
cancelledCollection.done();
assert.equal(cancelledCollection.cancelled, true);
